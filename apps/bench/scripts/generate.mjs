#!/usr/bin/env node
/**
 * Scales the bench app: writes N deterministic "domain" modules under
 * `lunora/domains/` (gitignored, except the `schema.ts` stub) shaped like the hand-written core —
 * `.shardBy("organizationId")` tables with indexes plus the odd `.global()` lookup
 * table, queries / mutations / internal jobs / actions built on `lib/crpc`, tenant
 * RLS, zod validators through `v.from`, and the occasional scheduler, queue or AI
 * hook. Nothing here is a stub that the bundler could drop: every module
 * evaluates its builder chains and validators at load, like a real one.
 *
 * A share of domains (`--heavy-share`) also gets an `integrations.ts` action module
 * built on a real third-party SDK — S3, an e2b sandbox, protobuf, tldts or an
 * OpenAI provider. Only that module imports the SDK, so the generated function
 * registry is its sole importer: the profile that let a lazy registry defer the
 * heavy dependencies of the app behind #1166.
 *
 *   node scripts/generate.mjs --domains 12
 *   node scripts/generate.mjs --domains 12 --heavy-share 0.5
 *   node scripts/generate.mjs --preset customer   # ≈ 1,000 functions / 130 tables, heavy SDKs in half the domains
 *   node scripts/generate.mjs --domains 0         # back to the committed core-only state
 */
