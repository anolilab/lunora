/** Writes `domains` domain modules (0 restores the committed state); returns what was generated. */
export const generate = ({ domains }) => {
    const root = join(appDirectory, "lunora", "domains");

    for (const entry of readdirSync(root, { withFileTypes: true })) {
        if (entry.isDirectory()) {
            rmSync(join(root, entry.name), { force: true, recursive: true });
        }
    }

    if (domains === 0) {
        writeFileSync(join(root, "schema.ts"), emptySchema, "utf8");

        return { domains: 0, modules: 0, tables: 0 };
    }

    const tables = [];
    let modules = 0;

    for (let index = 0; index < domains; index++) {
        const key = domainKey(index);
        const shape = shapeOf(index);
        const directory = join(root, key);
        const files = {
            "admin.ts": adminModule(key, shape),
            "jobs.ts": jobsModule(key, shape),
            "lines.ts": linesModule(key),
            "mutations.ts": recordMutationsModule(key, shape),
            "queries.ts": recordQueriesModule(key),
            "validators.ts": validatorsModule(key),
            ...(shape.notes ? { "notes.ts": notesModule(key) } : {}),
            ...(shape.catalog ? { "catalog.ts": catalogModule(key) } : {}),
        };

        mkdirSync(directory, { recursive: true });

        for (const [name, source] of Object.entries(files)) {
            writeFileSync(join(directory, name), source, "utf8");
        }

        modules += Object.keys(files).length;
        tables.push(...tableDefinitions(key, shape));
    }

    writeFileSync(
        join(root, "schema.ts"),
        `${header("*")}import { definePlugin, defineSchemaExtension, defineTable, v } from "lunorash/server";

export const domains = definePlugin("dom", {
    extension: defineSchemaExtension("dom", {
        tables: {
${tables.join("\n")}
        },
    }),
});
`,
        "utf8",
    );

    return { domains, modules, tables: tables.length };
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const { values } = parseArgs({ options: { domains: { type: "string" }, preset: { type: "string" } } });
    const domains = values.preset === undefined ? Number(values.domains ?? 0) : PRESETS[values.preset]?.domains;

    if (domains === undefined || !Number.isInteger(domains) || domains < 0) {
        throw new Error(`pass --domains <n ≥ 0> or --preset ${Object.keys(PRESETS).join("|")}`);
    }

    process.stdout.write(`${JSON.stringify(generate({ domains }))}\n`);
}
