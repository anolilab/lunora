import type { ExecutionContextLike, ShardNamespaceLike } from "@cirrus/runtime";
// `@cirrus/svelte/worker` is the socket-free composition entry: it wraps a
// SvelteKit Cloudflare Worker handler as the `httpRouter` of Cirrus's
// `composeWorker`, so `/_cirrus/*` hits Cirrus and everything else delegates to
// SvelteKit. ONE worker, ONE deploy (PLAN4 §3, class-B).
import { withCirrus } from "@cirrus/svelte/worker";
// The handler `@sveltejs/adapter-cloudflare` emits for SvelteKit's SSR + routes.
// This import resolves after the first `vite build` produces the adapter output;
// `cirrus dev` proxies SvelteKit's dev server, so it's only needed for the build.
// @ts-expect-error -- generated by `@sveltejs/adapter-cloudflare` at build time
import svelteKitWorker from "../.svelte-kit/cloudflare/_worker.js";

import { CIRRUS_FUNCTIONS } from "../cirrus/_generated/functions.js";
import { openApiSpec } from "../cirrus/_generated/openapi.js";
import { createShardDO } from "../cirrus/_generated/shard.js";

/**
 * The Durable Object that backs every shard's SQLite state. `createShardDO`
 * folds the generated dispatch table + live schema into the base `ShardDO`; the
 * class is bound as `SHARD` in `wrangler.jsonc`. Because this single worker
 * exports it, SvelteKit's SSR plane and Cirrus's realtime plane share one
 * Durable Object namespace — no double bundling (PLAN4 §5 risk #4).
 */
export const ShardDO = createShardDO();

interface Env {
    SHARD: ShardNamespaceLike;
}

/**
 * Single-worker entry (PLAN4 §3, class-B — "own CF adapter, hook-injection").
 *
 * `withCirrus` composes SvelteKit's adapter-emitted handler with Cirrus's
 * realtime plane: the reserved `/_cirrus/{rpc,ws,admin}` endpoints route into
 * Cirrus (forwarded to the `SHARD` Durable Object), and **everything else** —
 * pages, SvelteKit endpoints, and the `+page.ts` loaders that now call Cirrus
 * SAME-ORIGIN — delegates to SvelteKit. A SvelteKit render that throws is
 * contained at the seam as a plain 500 and can never take down `/_cirrus/*`.
 *
 * Cirrus options come from a factory so `env.SHARD` (a per-request binding) wires
 * into the shard namespace. Grow it by adding `auth`, `routes`, storage/admin
 * introspectors, etc. — the same options `createWorker` accepts.
 */
export default withCirrus(svelteKitWorker, (env) => ({
    // Exposes /_cirrus/admin/functions for the studio's function runner.
    functions: CIRRUS_FUNCTIONS,
    // The generated OpenAPI document backs the studio's API-reference tab.
    openApiSpec,
    // better-auth / OAuth callbacks etc. mount here; empty to start.
    routes: {},
    shardDO: (env as Env).SHARD,
}));

// Re-export the worker's scheduled hook surface for completeness; `withCirrus`
// returns `{ fetch, scheduled }`. The default export above already carries both.
export type WorkerEnv = Env;
export type { ExecutionContextLike };
