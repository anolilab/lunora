import type { FunctionIR, SchemaIR, ValidatorIR } from "./ir.js";

export const GENERATED_HEADER = "// GENERATED by @cirrus/codegen — do not edit.\n// Run `cirrus codegen` to regenerate.\n\n";

/** Map a {@link ValidatorIR} kind to its TS type. */
const validatorToType = (validator: ValidatorIR): string => {
    switch (validator.kind) {
        case "any":
            return "unknown";
        case "array":
            return `Array<${validator.inner ? validatorToType(validator.inner) : "unknown"}>`;
        case "bigint":
            return "bigint";
        case "boolean":
            return "boolean";
        case "bytes":
            return "ArrayBuffer";
        case "id":
            return `Id<"${validator.tableName ?? "_unknown_"}">`;
        case "null":
            return "null";
        case "number":
            return "number";
        case "object":
            return validator.shape
                ? `{ ${Object.entries(validator.shape)
                    .map(([key, child]) => `${key}: ${validatorToType(child)}`)
                    .join("; ")} }`
                : "Record<string, unknown>";
        case "optional":
            return `${validator.inner ? validatorToType(validator.inner) : "unknown"} | undefined`;
        case "string":
            return "string";
        case "union":
            return validator.members && validator.members.length > 0 ? validator.members.map((member) => validatorToType(member)).join(" | ") : "never";
        default:
            return "unknown";
    }
};

const renderArgsType = (args: Record<string, ValidatorIR>): string => {
    const entries = Object.entries(args);

    if (entries.length === 0) {
        return "{}";
    }

    return `{ ${entries
        .map(([key, validator]) => {
            if (validator.kind === "optional") {
                // Emit `key?: Inner` rather than `key?: Inner | undefined`.
                const inner = validator.inner ? validatorToType(validator.inner) : "unknown";

                return `${key}?: ${inner}`;
            }

            return `${key}: ${validatorToType(validator)}`;
        })
        .join("; ")} }`;
};

/** Emit `_generated/dataModel.ts` — `Doc<"name">` + `Id<"name">` for every table. */
export const emitDataModel = (schema: SchemaIR): string => {
    const tableNames = schema.tables.map((table) => `"${table.name}"`).join(" | ") || "never";

    const docs = schema.tables
        .map((table) => {
            const fields = Object.entries(table.shape)
                .map(([fieldName, validator]) => {
                    if (validator.kind === "optional") {
                        const inner = validator.inner ? validatorToType(validator.inner) : "unknown";

                        return `    ${fieldName}?: ${inner};`;
                    }

                    return `    ${fieldName}: ${validatorToType(validator)};`;
                })
                .join("\n");
            const body = fields ? `\n${fields}\n` : "";

            return `export interface Doc_${table.name} {\n    _id: Id<"${table.name}">;\n    _creationTime: number;${body}}`;
        })
        .join("\n\n");

    const docMap = schema.tables.map((table) => `    ${table.name}: Doc_${table.name};`).join("\n");

    return `${GENERATED_HEADER}export type TableName = ${tableNames};

export type Id<TName extends string> = string & { readonly __table: TName };

${docs}

export interface DataModel {
${docMap}
}

export type Doc<T extends keyof DataModel> = DataModel[T];
`;
};

/** Emit `_generated/api.ts` — the typed `api.*` registry. */
export const emitApi = (functions: ReadonlyArray<FunctionIR>): string => {
    // Group functions by file path (namespace).
    const namespaces = new Map<string, FunctionIR[]>();

    for (const function_ of functions) {
        const list = namespaces.get(function_.filePath) ?? [];

        list.push(function_);
        namespaces.set(function_.filePath, list);
    }

    const renderNamespace = ([file, list]: [string, FunctionIR[]]): string => {
        const members = list
            .map((function_) => {
                // We emit `FunctionReference<Kind, ArgsObj, Return>` so the
                // generated `api.*` references plug directly into
                // `useQuery`/`useMutation` from `@cirrus/react` (and
                // `client.query` / `client.mutation` from `@cirrus/client`).
                // The phantom `Kind`/`Args`/`Return` parameters carry the
                // info downstream hooks need to infer call signatures.
                const argsType = renderArgsType(function_.args);

                return `        ${function_.exportName}: FunctionReference<"${function_.kind}", ${argsType}, unknown>;`;
            })
            .join("\n");

        return `    ${file.replace(/[^\dA-Za-z]/gu, "_")}: {\n${members}\n    };`;
    };

    const sortedNamespaces = [...namespaces.entries()].sort(([a], [b]) => a.localeCompare(b));

    return `${GENERATED_HEADER}import { anyApi } from "@cirrus/server/types";
import type { FunctionReference } from "@cirrus/client";

import type { Id } from "./dataModel.js";

export interface ApiTypes {
${sortedNamespaces.map((entry) => renderNamespace(entry)).join("\n")}
}

export const api = anyApi as unknown as ApiTypes;
`;
};

/** Emit `_generated/server.ts` — typed `query`/`mutation`/`action` factories. */
export const emitServer = (): string => {
    return `${GENERATED_HEADER}export { action, mutation, query } from "@cirrus/server";
export type { ActionCtx, MutationCtx, QueryCtx } from "@cirrus/server";

export type { DataModel, Doc, Id } from "./dataModel.js";
`;
};
