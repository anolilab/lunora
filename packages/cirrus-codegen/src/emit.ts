import type { FunctionIR, SchemaIR, ValidatorIR } from "./ir.js";
import { sanitizeNamespace } from "./paths.js";

export const GENERATED_HEADER = "// GENERATED by @cirrus/codegen — do not edit.\n// Run `cirrus codegen` to regenerate.\n\n";

/** Map a {@link ValidatorIR} kind to its TS type. */
const validatorToType = (validator: ValidatorIR): string => {
    switch (validator.kind) {
        case "any": {
            return "unknown";
        }
        case "array": {
            return `Array<${validator.inner ? validatorToType(validator.inner) : "unknown"}>`;
        }
        case "bigint": {
            return "bigint";
        }
        case "boolean": {
            return "boolean";
        }
        case "bytes": {
            return "ArrayBuffer";
        }
        case "id": {
            return `Id<"${validator.tableName ?? "_unknown_"}">`;
        }
        case "literal": {
            // `literalValue` is the verbatim source text (e.g. `"admin"`, `42`,
            // `true`, `null`) — already a valid TS literal type.
            return validator.literalValue ?? "unknown";
        }
        case "null": {
            return "null";
        }
        case "number": {
            return "number";
        }
        case "object": {
            return validator.shape
                ? `{ ${Object.entries(validator.shape)
                    .map(([key, child]) => `${key}: ${validatorToType(child)}`)
                    .join("; ")} }`
                : "Record<string, unknown>";
        }
        case "optional": {
            return `${validator.inner ? validatorToType(validator.inner) : "unknown"} | undefined`;
        }
        case "record": {
            const key = validator.keyType ? validatorToType(validator.keyType) : "string";
            const value = validator.valueType ? validatorToType(validator.valueType) : "unknown";

            return `Record<${key}, ${value}>`;
        }
        case "string": {
            return "string";
        }
        case "union": {
            return validator.members && validator.members.length > 0 ? validator.members.map((member) => validatorToType(member)).join(" | ") : "never";
        }
        default: {
            return "unknown";
        }
    }
};

const renderArgsType = (args: Record<string, ValidatorIR>): string => {
    const entries = Object.entries(args);

    if (entries.length === 0) {
        return "{}";
    }

    return `{ ${entries
        .map(([key, validator]) => {
            if (validator.kind === "optional") {
                // Emit `key?: Inner` rather than `key?: Inner | undefined`.
                const inner = validator.inner ? validatorToType(validator.inner) : "unknown";

                return `${key}?: ${inner}`;
            }

            return `${key}: ${validatorToType(validator)}`;
        })
        .join("; ")} }`;
};

/** Emit `_generated/dataModel.ts` — `Doc<"name">` + `Id<"name">` for every table. */
export const emitDataModel = (schema: SchemaIR): string => {
    const tableNames = schema.tables.map((table) => `"${table.name}"`).join(" | ") || "never";

    const docs = schema.tables
        .map((table) => {
            const fields = Object.entries(table.shape)
                .map(([fieldName, validator]) => {
                    if (validator.kind === "optional") {
                        const inner = validator.inner ? validatorToType(validator.inner) : "unknown";

                        return `    ${fieldName}?: ${inner};`;
                    }

                    return `    ${fieldName}: ${validatorToType(validator)};`;
                })
                .join("\n");
            const body = fields ? `\n${fields}\n` : "";

            return `export interface Doc_${table.name} {\n    _id: Id<"${table.name}">;\n    _creationTime: number;${body}}`;
        })
        .join("\n\n");

    const docMap = schema.tables.map((table) => `    ${table.name}: Doc_${table.name};`).join("\n");

    // Per-table index name union — surfaced as `IndexName<"messages">` so
    // `TableReader.withIndex(name)` can be typed without a hand-rolled
    // overload per table.
    const indexNamesByTable = schema.tables
        .map((table) => {
            const names = table.indexes.map((index) => `"${index.name}"`).join(" | ");

            return `    ${table.name}: ${names || "never"};`;
        })
        .join("\n");

    const searchIndexNamesByTable = schema.tables
        .map((table) => {
            const names = table.searchIndexes.map((index) => `"${index.name}"`).join(" | ");

            return `    ${table.name}: ${names || "never"};`;
        })
        .join("\n");

    return `${GENERATED_HEADER}export type TableName = ${tableNames};

export type Id<TName extends string> = string & { readonly __table: TName };

${docs}

export interface DataModel {
${docMap}
}

export type Doc<T extends keyof DataModel> = DataModel[T];

/**
 * Per-table index name union. \`never\` for tables without secondary indexes.
 * Used by \`TableReader.withIndex()\` to constrain callers to declared names.
 */
export interface IndexNamesByTable {
${indexNamesByTable}
}

export type IndexName<T extends keyof DataModel> = IndexNamesByTable[T];

/** Per-table search-index name union. \`never\` for tables without searchIndex. */
export interface SearchIndexNamesByTable {
${searchIndexNamesByTable}
}

export type SearchIndexName<T extends keyof DataModel> = SearchIndexNamesByTable[T];
`;
};

/** Emit `_generated/api.ts` — the typed `api.*` registry. */
export const emitApi = (functions: ReadonlyArray<FunctionIR>): string => {
    // Group functions by file path (namespace).
    const namespaces = new Map<string, FunctionIR[]>();

    for (const function_ of functions) {
        const list = namespaces.get(function_.filePath) ?? [];

        list.push(function_);
        namespaces.set(function_.filePath, list);
    }

    const renderNamespace = ([file, list]: [string, FunctionIR[]]): string => {
        const members = list
            .map((function_) => {
                // We emit `FunctionReference<Kind, ArgsObj, Return>` so the
                // generated `api.*` references plug directly into
                // `useQuery`/`useMutation` from `@cirrus/react` (and
                // `client.query` / `client.mutation` from `@cirrus/client`).
                // The phantom `Kind`/`Args`/`Return` parameters carry the
                // info downstream hooks need to infer call signatures.
                const argsType = renderArgsType(function_.args);

                return `        ${function_.exportName}: FunctionReference<"${function_.kind}", ${argsType}, ${function_.returnType}>;`;
            })
            .join("\n");

        return `    ${sanitizeNamespace(file)}: {\n${members}\n    };`;
    };

    const sortedNamespaces = [...namespaces.entries()].sort(([a], [b]) => a.localeCompare(b));

    return `${GENERATED_HEADER}import { anyApi } from "@cirrus/server/types";
import type { FunctionReference } from "@cirrus/client";

import type { Id } from "./dataModel.js";

export interface ApiTypes {
${sortedNamespaces.map((entry) => renderNamespace(entry)).join("\n")}
}

export const api = anyApi as unknown as ApiTypes;
`;
};

/**
 * Convert a raw file path into a JS-identifier-safe alias used as the
 * imported namespace inside `_generated/server.ts`. Keeps the path
 * recognisable in the generated source while satisfying the lexer.
 */
const moduleAlias = (filePath: string, index: number): string => `cirrus_${sanitizeNamespace(filePath)}_${index}`;

/**
 * Emit `_generated/server.ts` — re-exports of the user-facing factories
 * **plus** a static dispatch table that maps `${namespace}:${fnName}` keys
 * to the registered handler objects. A `ShardDO` subclass can plug this
 * straight into `handleRpc(functionPath, args)`.
 */
export const emitServer = (functions: ReadonlyArray<FunctionIR>): string => {
    // Group functions by file path so each module is imported once. The
    // generated alias mirrors the order discoverFunctions returns so output
    // is deterministic between runs.
    const moduleEntries = new Map<string, { alias: string; functions: FunctionIR[] }>();
    let moduleIndex = 0;

    for (const function_ of functions) {
        let entry = moduleEntries.get(function_.filePath);

        if (!entry) {
            entry = { alias: moduleAlias(function_.filePath, moduleIndex), functions: [] };
            moduleEntries.set(function_.filePath, entry);
            moduleIndex += 1;
        }

        entry.functions.push(function_);
    }

    const importLines = [...moduleEntries.entries()].map(([filePath, entry]) => `import * as ${entry.alias} from "../${filePath}.js";`).join("\n");

    const dispatchEntries = [...moduleEntries.entries()]
        .flatMap(([filePath, entry]) =>
            entry.functions.map(
                (function_) =>
                    `    "${sanitizeNamespace(filePath)}:${function_.exportName}": ${entry.alias}.${function_.exportName} as unknown as RegisteredCirrusFunction,`,
            ),
        )
        .join("\n");

    const dispatchBody = dispatchEntries.length > 0 ? `\n${dispatchEntries}\n` : "";
    const importBlock = importLines.length > 0 ? `${importLines}\n\n` : "";

    return `${GENERATED_HEADER}${importBlock}export { action, mutation, query } from "@cirrus/server";
export type { ActionCtx, MutationCtx, QueryCtx } from "@cirrus/server";

export type { DataModel, Doc, Id } from "./dataModel.js";

/**
 * Single registered function, narrowed to the shape \`handleRpc\` needs.
 * The real argument validators / return types are checked elsewhere — at
 * the dispatch site we erase to \`unknown\` so a single map can host every
 * registered function.
 */
export interface RegisteredCirrusFunction {
    kind: "action" | "mutation" | "query";
    args: Record<string, unknown>;
    handler: (context: unknown, args: Record<string, unknown>) => Promise<unknown> | unknown;
}

/**
 * Static dispatch table. The key matches the \`__cirrusRef\` the client
 * emits (\`api[namespace][fn].__cirrusRef === "namespace:fn"\`).
 */
export const CIRRUS_FUNCTIONS: Record<string, RegisteredCirrusFunction> = {${dispatchBody}};

/**
 * Resolve and invoke a registered function. Throws a CirrusError-shaped
 * object (404) when the path is unknown — the runtime's structural error
 * mapper turns that into the right HTTP status.
 */
export const dispatchCirrusFunction = async (functionPath: string, context: unknown, args: Record<string, unknown>): Promise<unknown> => {
    const registered = CIRRUS_FUNCTIONS[functionPath];

    if (!registered) {
        throw Object.assign(new Error(\`function not registered: \${functionPath}\`), {
            name: "CirrusError",
            code: "FUNCTION_NOT_FOUND",
            status: 404,
        });
    }

    return registered.handler(context, args);
};
`;
};
