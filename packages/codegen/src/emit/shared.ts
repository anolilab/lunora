/**
 * Import specifiers for the base packages the generated `_generated/*` files
 * reference (`@lunora/server` and its subpaths, `@lunora/do`).
 *
 * A project can depend on the granular `@lunora/*` packages OR on the single
 * `lunora` umbrella, which re-exports the same surface through subpaths
 * (`lunorash/server`, `lunorash/do`, …). Codegen picks the form per-project from the
 * declared dependencies (see `run-codegen`), so the umbrella shrinks the app's
 * `package.json` without the generated code drifting. Only the base set is
 * remapped — `@lunora/client` and the opt-in add-ons stay scoped because they
 * are installed separately either way.
 */
interface BaseSpecifiers {
    readonly client: string;
    readonly do: string;
    /** `ctx.flags` (OpenFeature) surface — `lunorash/flags` under the umbrella (the umbrella ships `./flags*` subpaths), else `@lunora/flags`. */
    readonly flags: string;
    readonly server: string;
    readonly serverDataModel: string;
    readonly serverDrizzle: string;
    readonly serverTypes: string;
    readonly values: string;
}

const baseSpecifiers = (useUmbrella = false): BaseSpecifiers =>
    useUmbrella
        ? {
              client: "lunorash/client",
              do: "lunorash/do",
              flags: "lunorash/flags",
              server: "lunorash/server",
              serverDataModel: "lunorash/server/data-model",
              serverDrizzle: "lunorash/server/drizzle",
              serverTypes: "lunorash/server/types",
              values: "lunorash/values",
          }
        : {
              client: "@lunora/client",
              do: "@lunora/do",
              flags: "@lunora/flags",
              server: "@lunora/server",
              serverDataModel: "@lunora/server/data-model",
              serverDrizzle: "@lunora/server/drizzle",
              serverTypes: "@lunora/server/types",
              values: "@lunora/values",
          };

/**
 * Matches the JS identifier subset we accept verbatim in emitted source.
 * Used to gate raw interpolation of table names, field names, etc. into
 * generated TS — anything outside the allowlist throws (E1) so we never
 * embed unescaped source from a `schema.ts`. Table names are additionally
 * gated earlier, at discovery, by `TABLE_NAME_IDENTIFIER_RE` in
 * `discover/schema.ts` — that is the user-facing boundary (a pinpointed
 * `file:line:column` diagnostic on the schema); this E1 throw is
 * defense-in-depth behind it and should never fire for table names in
 * practice. Must stay in sync with the discovery-side copy.
 */
const IDENTIFIER_RE = /^[A-Za-z_$][\w$]*$/u;

/** Path fragment used inside an emitted `import "../${filePath}.js"`. */
const IMPORT_PATH_RE: RegExp = /^[\w./-]+$/u;

/**
 * Throw unless `value` can be emitted as a BINDING: an identifier that is not
 * a reserved word. Export, class and binding names are imported and declared
 * as bindings (`import { <name> }`, `class <name>`), where `default` or
 * `delete` is a syntax error.
 */
const assertIdentifier = (value: string, context: string): void => {
    if (!IDENTIFIER_RE.test(value) || RESERVED_JS_WORDS.has(value)) {
        throw new LunoraError("INTERNAL", `@lunora/codegen: ${context} is not a valid JS identifier: ${JSON.stringify(value)}`);
    }
};

/**
 * Throw unless `value` can be emitted as a bare object KEY or member name
 * (`<name>: …`, `t.<name>`): any identifier, reserved words included — a column
 * may be called `default`.
 */
const assertPropertyIdentifier = (value: string, context: string): void => {
    if (!IDENTIFIER_RE.test(value)) {
        throw new LunoraError("INTERNAL", `@lunora/codegen: ${context} is not a valid JS identifier: ${JSON.stringify(value)}`);
    }
};

/** Upper-case the first character — turns an emitted value name into its PascalCase type name. */
const pascalCase = (value: string): string => value.charAt(0).toUpperCase() + value.slice(1);

/**
 * Emit a TS interface property: bare `name: T` when `name` is a JS identifier,
 * otherwise a quoted property name (`"weird name": T`). Quoted property names
 * are valid TS interface members, so callers don't have to filter upstream.
 */
const renderPropertyKey = (fieldName: string): string => (IDENTIFIER_RE.test(fieldName) ? fieldName : JSON.stringify(fieldName));

/**
 * Emit a key for a runtime OBJECT LITERAL — bare when it is a JS identifier,
 * otherwise quoted, and `__proto__` as a computed key.
 *
 * `__proto__` passes {@link IDENTIFIER_RE} and even survives quoting, but in a
 * value position `{ __proto__: x }` and `{ "__proto__": x }` are both the
 * prototype SETTER: neither creates an own property, so the entry silently
 * vanishes from the emitted object. `{ ["__proto__"]: x }` is an ordinary own
 * property. {@link renderPropertyKey} stays correct for TYPE positions, where
 * `__proto__` is just a member name and a computed key would not even parse.
 */
const renderObjectKey = (fieldName: string): string => (fieldName === "__proto__" ? `[${JSON.stringify(fieldName)}]` : renderPropertyKey(fieldName));

/** Group entries by `filePath`, entries sorted by file for deterministic output. */
const groupByFileSorted = <T extends { filePath: string }>(entries: ReadonlyArray<T>): [string, T[]][] => {
    const namespaces = new Map<string, T[]>();

    for (const entry of entries) {
        const list = namespaces.get(entry.filePath) ?? [];

        list.push(entry);
        namespaces.set(entry.filePath, list);
    }

    return [...namespaces.entries()].toSorted(([a], [b]) => a.localeCompare(b));
};

interface NamespaceNode<T> {
    children: Map<string, NamespaceNode<T>>;
    /** The entries of the file this node stands for, and that file. */
    file?: { entries: T[]; path: string };
}

/**
 * Render entries grouped by file as nested key paths, the shape of `api.*`:
 * `lunora/billing/invoices.ts` → `billing: { invoices: { … } }`. A file and a
 * folder of the same name share a node (`lunora/billing.ts` + `lunora/billing/`),
 * so an export named like a file in that folder is rejected — both would claim
 * `api.billing.<name>`. Checked here rather than in discovery because synthetic
 * entries (agents, custom mutators) reach the tree too.
 *
 * Members and nested keys both emit in alphabetical order, so the output is
 * stable however the entries arrive. `renderLeaf` renders one member without indentation. `position` picks the
 * key quoting and block terminator: an interface (`type`) or an object literal
 * (`value`).
 */
const renderNamespaceTree = <T extends { exportName: string; filePath: string }>(
    entries: ReadonlyArray<T>,
    renderLeaf: (entry: T) => string,
    position: "type" | "value",
): string => {
    const [renderKey, terminator] = position === "type" ? [renderPropertyKey, ";"] : [renderObjectKey, ","];
    const root: NamespaceNode<T> = { children: new Map() };

    for (const [path, list] of groupByFileSorted(entries)) {
        let node = root;

        for (const segment of namespaceSegments(path)) {
            let child = node.children.get(segment);

            if (child === undefined) {
                child = { children: new Map() };
                node.children.set(segment, child);
            }

            node = child;
        }

        node.file = { entries: list, path };
    }

    /** Any file under `node`, to name in a collision error. */
    const fileUnder = (node: NamespaceNode<T>): string => node.file?.path ?? fileUnder(node.children.values().next().value as NamespaceNode<T>);

    const render = (node: NamespaceNode<T>, depth: number): string[] => {
        const indent = "    ".repeat(depth);
        const { entries: list = [], path = "" } = node.file ?? {};
        const clash = list.find((entry) => node.children.has(entry.exportName));

        if (clash !== undefined) {
            const other = fileUnder(node.children.get(clash.exportName) as NamespaceNode<T>);

            throw new LunoraError(
                "NAMESPACE_COLLISION",
                `Namespace collision: the export "${clash.exportName}" of "${path}" and "${other}" both resolve to api.${[...namespaceSegments(path), clash.exportName].join(".")}. Rename the export or the folder.`,
            );
        }

        const leaves = list.toSorted((a, b) => a.exportName.localeCompare(b.exportName)).map((entry) => `${indent}${renderLeaf(entry)}`);
        const nested = [...node.children.entries()]
            .toSorted(([a], [b]) => a.localeCompare(b))
            .map(([key, child]) => `${indent}${renderKey(key)}: {\n${render(child, depth + 1).join("\n")}\n${indent}}${terminator}`);

        return [...leaves, ...nested];
    };

    return render(root, 1).join("\n");
};

/** Scalar `ValidatorIR` kinds whose TS type is a fixed string with no recursion. */
const SCALAR_TYPE_BY_KIND: Record<string, string> = {
    any: "unknown",
    bigint: "bigint",
    boolean: "boolean",
    bytes: "ArrayBuffer",
    // Epoch-millisecond numbers; the distinction is semantic only.
    date: "number",
    // A geographic point stored as a `{ lat, lng }` JSON object.
    geoPoint: "{ lat: number; lng: number }",
    null: "null",
    number: "number",
    // The key of a stored R2 object — a string; the distinction is semantic only.
    storage: "string",
    string: "string",
    timestamp: "number",
};

/**
 * Render a `v.literal(...)` type. `literalValue` is the verbatim source text
 * (e.g. `"admin"`, `42`, `true`, `null`). Validated against a strict TS-literal
 * allowlist so arbitrary expressions can't be embedded into emitted types.
 */
const literalToType = (value: string | undefined): string => {
    if (value === undefined) {
        return "unknown";
    }

    if (!LITERAL_VALUE_RE.test(value)) {
        throw new LunoraError(
            "INTERNAL",
            `@lunora/codegen: v.literal() argument is not a parseable string/number/boolean/null literal: ${JSON.stringify(value)}`,
        );
    }

    return value;
};

/**
 * Map a {@link ValidatorIR} to its TS type.
 *
 * `.nullable()` is recorded on the column meta rather than as a kind, and it
 * admits `null` at runtime (a nullable column reads back as SQL NULL). So every
 * type rendered from the IR — `Doc_*`, `Insert_*`, procedure args, drizzle
 * `$type<…>` — widens here, or `doc.note.length` typechecks against a `null`.
 */
const validatorToType = (validator: ValidatorIR): string =>
    // eslint-disable-next-line @typescript-eslint/no-use-before-define -- mutual recursion: kindToType re-enters validatorToType for nested validators
    validator.column?.notNull === false ? `${kindToType(validator)} | null` : kindToType(validator);

/** The TS type of a {@link ValidatorIR}'s kind, before {@link validatorToType}'s `.nullable()` widening. */
const kindToType = (validator: ValidatorIR): string => {
    const scalar = SCALAR_TYPE_BY_KIND[validator.kind];

    if (scalar !== undefined) {
        return scalar;
    }

    switch (validator.kind) {
        case "array": {
            return `Array<${validator.inner ? validatorToType(validator.inner) : "unknown"}>`;
        }
        case "from": {
            // Recovered from the wrapped Standard Schema's `~standard.types.output`
            // by `resolveStandardSchemaType`; `unknown` when it could not be
            // rendered safely. Deliberately NOT in
            // `SCALAR_TYPE_BY_KIND` — that map short-circuits before this switch,
            // which silently made the recovered type unreachable.
            return validator.tsType ?? "unknown";
        }
        case "id": {
            const tableName = validator.tableName ?? "_unknown_";

            assertIdentifier(tableName, "v.id() table name");

            return `Id<"${tableName}">`;
        }
        case "literal": {
            return literalToType(validator.literalValue);
        }
        case "object": {
            if (!validator.shape) {
                return "Record<string, unknown>";
            }

            // Same optionality rule `renderArgsType` applies at the top level of
            // `.input()`. Rendering an optional child as a required key typed
            // `T | undefined` forced every caller of a partial-update shape to
            // pass explicit `undefined`s, which a `{...args.patch}` spread then
            // carried into `ctx.db.patch` — a partial update that is not partial.
            const fields = Object.entries(validator.shape)
                // eslint-disable-next-line @typescript-eslint/no-use-before-define -- mutual recursion: renderShapeEntry re-enters validatorToType for the property's type
                .map(([key, child]) => renderShapeEntry(key, child))
                .join("; ");

            return `{ ${fields} }`;
        }
        case "optional": {
            return `${validator.inner ? validatorToType(validator.inner) : "unknown"} | undefined`;
        }
        case "record": {
            const key = validator.keyType ? validatorToType(validator.keyType) : "string";
            const value = validator.valueType ? validatorToType(validator.valueType) : "unknown";

            return `Record<${key}, ${value}>`;
        }
        case "union": {
            return validator.members && validator.members.length > 0 ? validator.members.map((member) => validatorToType(member)).join(" | ") : "never";
        }
        default: {
            return "unknown";
        }
    }
};

/**
 * Render one `{key: type}` entry of an object shape, mapping a validator the
 * runtime parses an ABSENT field for to the optional PROPERTY `key?: T` rather
 * than the required `key: T | undefined`.
 *
 * The distinction is not cosmetic: a required key typed `T | undefined` obliges
 * a caller to name every field, so a partial-update argument stops being
 * partial. Used at every depth — top-level `.input()` and nested `v.object()`
 * alike, which is what keeps the two in agreement.
 *
 * Optionality is {@link acceptsAbsentIr}, the shared `@lunora/values` predicate,
 * NOT `kind === "optional"`. `v.any()` returns its input unchanged, so an absent
 * arg parses and `Infer` types it `data?: unknown`; emitting `data: unknown`
 * made a handler's own `args` unassignable to the `_generated/api.ts` reference
 * of a procedure declaring the identical validator (issue #688). The `optional`
 * branch survives only because it additionally STRIPS the `| undefined` the
 * wrapper adds.
 */
const renderShapeEntry = (key: string, validator: ValidatorIR): string => {
    const propertyKey = renderPropertyKey(key);

    if (validator.kind === "optional") {
        // Emit `key?: Inner` rather than `key?: Inner | undefined`.
        const inner = validator.inner ? validatorToType(validator.inner) : "unknown";

        return `${propertyKey}?: ${inner}`;
    }

    // `v.any()`, and a `v.union(...)` with an `any`/optional member: the type
    // already admits `undefined`, so it is rendered verbatim under an optional key.
    if (acceptsAbsentIr(validator)) {
        return `${propertyKey}?: ${validatorToType(validator)}`;
    }

    return `${propertyKey}: ${validatorToType(validator)}`;
};

const renderArgsType = (args: Record<string, ValidatorIR>): string => {
    const entries = Object.entries(args);

    if (entries.length === 0) {
        return "{}";
    }

    return `{ ${entries.map(([key, validator]) => renderShapeEntry(key, validator)).join("; ")} }`;
};

/**
 * A field is optional on **insert** when it is `v.optional(...)` or declares a
 * `.default()`/`.$defaultFn()` (codegen records the latter as `column.hasDefault`).
 */
const isOptionalOnInsert = (validator: ValidatorIR): boolean => validator.kind === "optional" || Boolean(validator.column?.hasDefault);

/** The wrapped validator of a `v.optional(...)`, or the validator itself. */
const unwrapOptional = (validator: ValidatorIR): ValidatorIR => (validator.kind === "optional" && validator.inner ? validator.inner : validator);

/**
 * Render an `Insert_<table>` interface: the document shape as accepted by
 * `ctx.db.<table>.insert(...)`. System fields (`_id`, `_creationTime`) are
 * always optional (minted by the runtime); user fields follow
 * {@link isOptionalOnInsert}.
 */
const renderInsertInterface = (table: TableIR): string => {
    assertIdentifier(table.name, "table name");

    const fields = Object.entries(table.shape)
        .map(([fieldName, validator]) => {
            const inner = unwrapOptional(validator);
            const type = validatorToType(inner);
            const propertyKey = renderPropertyKey(fieldName);

            return isOptionalOnInsert(validator) ? `    ${propertyKey}?: ${type};` : `    ${propertyKey}: ${type};`;
        })
        .join("\n");
    const body = fields ? `\n${fields}\n` : "";

    return `export interface Insert_${table.name} {\n    _id?: Id<"${table.name}">;\n    _creationTime?: number;${body}}`;
};

