import { existsSync, readFileSync } from "node:fs";
import { basename, join } from "node:path";

const WRANGLER_FILENAMES = ["wrangler.jsonc", "wrangler.json"];

/** Top-level string value of `key` in a wrangler file; the first match wins, which is the top level in every real config. */
const wranglerString = (projectRoot: string, key: string): string | undefined => {
    for (const filename of WRANGLER_FILENAMES) {
        const path = join(projectRoot, filename);

        if (existsSync(path)) {
            return new RegExp(String.raw`"${key}"\s*:\s*"([^"]+)"`).exec(readFileSync(path, "utf8"))?.[1];
        }
    }

    return undefined;
};

/**
 * The companion Worker's name: the main wrangler `name` with `-advisor` appended, falling back to the project
 * folder name so a project without a wrangler config still gets a valid, deterministic name.
 */
const companionName = (projectRoot: string): string => `${wranglerString(projectRoot, "name") ?? basename(projectRoot)}-advisor`;

const emitCompanionWrangler = (projectRoot: string): string => {
    const compatibilityDate = wranglerString(projectRoot, "compatibility_date");

    return `${JSON.stringify(
        {
            $schema: "node_modules/wrangler/config-schema.json",
            ...(compatibilityDate === undefined ? {} : { compatibility_date: compatibilityDate }),
            main: "src/worker.ts",
            name: companionName(projectRoot),
        },
        undefined,
        4,
    )}\n`;
};

/**
 * Self-contained on purpose: the companion deploys as its own Worker, so it cannot import `@lunora/*` or Node
 * built-ins. The check mirrors `createCompanionHandler` in `@lunora/config`.
 */
const emitCompanionWorker = (proceduresJson: string): string => `// Generated by @lunora/codegen. Do not edit.
// Serves the advisor procedure list to a hosted Studio. The admin token is a Worker secret.
interface Env {
    LUNORA_ADMIN_TOKEN?: string;
}

const PROCEDURES = ${JSON.stringify(proceduresJson)};

const ADVISOR_PROCEDURES_PATH = "/__lunora/advisor-procedures";

const constantTimeEqual = (a: string, b: string): boolean => {
    const encoder = new TextEncoder();
    const left = encoder.encode(a);
    const right = encoder.encode(b);
    let difference = left.length ^ right.length;

    for (let index = 0; index < Math.max(left.length, right.length); index += 1) {
        difference |= (left[index] ?? 0) ^ (right[index] ?? 0);
    }

    return difference === 0;
};

const bearer = (request: Request): string | undefined => {
    const header = request.headers.get("Authorization");

    return header?.startsWith("Bearer ") ? header.slice("Bearer ".length) : undefined;
};

export default {
    fetch(request: Request, env: Env): Response {
        const presented = bearer(request);

        // 401 before the path is read, so the route cannot be probed without the token.
        if (presented === undefined || env.LUNORA_ADMIN_TOKEN === undefined || env.LUNORA_ADMIN_TOKEN === "" || !constantTimeEqual(presented, env.LUNORA_ADMIN_TOKEN)) {
            return Response.json({ error: "unauthorized" }, { status: 401 });
        }

        if (new URL(request.url).pathname !== ADVISOR_PROCEDURES_PATH) {
            return Response.json({ error: "not found" }, { status: 404 });
        }

        if (request.method !== "GET") {
            return Response.json({ error: "GET only" }, { status: 405 });
        }

        return new Response(PROCEDURES, { headers: { "Content-Type": "application/json" }, status: 200 });
    },
};
`;

/** The `_generated/companion/` files keyed relative to that folder; `{}` when the flag is off, which removes the folder. */
const emitCompanion = (projectRoot: string, procedures: ReadonlyArray<unknown>, enabled: boolean): Record<string, string> => {
    if (!enabled) {
        return {};
    }

    const proceduresJson = `${JSON.stringify(procedures, undefined, 2)}\n`;

    return {
        "advisor-procedures.json": proceduresJson,
        "src/worker.ts": emitCompanionWorker(proceduresJson),
        "wrangler.jsonc": emitCompanionWrangler(projectRoot),
    };
};

export default emitCompanion;
