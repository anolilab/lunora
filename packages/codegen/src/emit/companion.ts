import { companionName, wranglerString } from "../companion";

const emitCompanionWrangler = (projectRoot: string): string => {
    const compatibilityDate = wranglerString(projectRoot, "compatibility_date");

    return `${JSON.stringify(
        {
            $schema: "node_modules/wrangler/config-schema.json",
            ...(compatibilityDate === undefined ? {} : { compatibility_date: compatibilityDate }),
            main: "src/worker.ts",
            name: companionName(projectRoot),
            // No address of its own: the app's Worker reaches it over the service binding only.
            workers_dev: false,
        },
        undefined,
        4,
    )}\n`;
};

/**
 * Self-contained on purpose: the companion deploys as its own Worker, so it cannot import `@lunora/*` or Node
 * built-ins. It carries no admin check of its own: `workers_dev` is off and it has no route, so the only caller
 * is the app's Worker over the `ADVISOR_COMPANION` binding, and that Worker checks the admin token first.
 */
const emitCompanionWorker = (proceduresJson: string): string => `// Generated by @lunora/codegen. Do not edit.
// Serves the advisor procedure list to the app's Worker, which forwards it to a hosted Studio after the admin check.
const PROCEDURES = ${JSON.stringify(proceduresJson)};

const ADVISOR_PROCEDURES_PATH = "/__lunora/advisor-procedures";

export default {
    fetch(request: Request): Response {
        if (new URL(request.url).pathname !== ADVISOR_PROCEDURES_PATH) {
            return Response.json({ error: "not found" }, { status: 404 });
        }

        if (request.method !== "GET") {
            return Response.json({ error: "GET only" }, { status: 405 });
        }

        return new Response(PROCEDURES, { headers: { "Content-Type": "application/json" }, status: 200 });
    },
};
`;

/** The `_generated/companion/` files keyed relative to that folder; `{}` when the flag is off, which removes the folder. */
const emitCompanion = (projectRoot: string, procedures: ReadonlyArray<unknown>, enabled: boolean): Record<string, string> => {
    if (!enabled) {
        return {};
    }

    // The same `{ procedures }` document the dev host serves, so the Studio reads one shape from either.
    const proceduresJson = `${JSON.stringify({ procedures }, undefined, 2)}\n`;

    return {
        "advisor-procedures.json": proceduresJson,
        "src/worker.ts": emitCompanionWorker(proceduresJson),
        "wrangler.jsonc": emitCompanionWrangler(projectRoot),
    };
};

export default emitCompanion;
